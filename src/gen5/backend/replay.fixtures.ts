/** A format of `argCount` arguments, each written as a halfword. */
const halves = (code: number, argCount: number): ArgFormat => ({
  code,
  argCount,
  puts: Array.from({ length: argCount }, (_, arg) => ({
    bytes: 2,
    fields: [{ arg, mask: 0xffff, shift: 0 }],
  })),
})

