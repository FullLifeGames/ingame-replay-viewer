#include "irv_sine.h"

// round(sin(i * pi / 128) * 0x4000) for i 0-64; scripts/wasm-layer-bios.test.ts checks every
// entry against the formula.
const int16_t gIrvSineQuarter[IRV_SINE_QUARTER + 1] = {
    0x0000, 0x0192, 0x0324, 0x04B5, 0x0646, 0x07D6, 0x0964, 0x0AF1,
    0x0C7C, 0x0E06, 0x0F8D, 0x1112, 0x1294, 0x1413, 0x1590, 0x1709,
    0x187E, 0x19EF, 0x1B5D, 0x1CC6, 0x1E2B, 0x1F8C, 0x20E7, 0x223D,
    0x238E, 0x24DA, 0x2620, 0x2760, 0x289A, 0x29CE, 0x2AFB, 0x2C21,
    0x2D41, 0x2E5A, 0x2F6C, 0x3076, 0x3179, 0x3274, 0x3368, 0x3453,
    0x3537, 0x3612, 0x36E5, 0x37B0, 0x3871, 0x392B, 0x39DB, 0x3A82,
    0x3B21, 0x3BB6, 0x3C42, 0x3CC5, 0x3D3F, 0x3DAF, 0x3E15, 0x3E72,
    0x3EC5, 0x3F0F, 0x3F4F, 0x3F85, 0x3FB1, 0x3FD4, 0x3FEC, 0x3FFB,
    0x4000,
};

int32_t IrvSine(uint8_t step)
{
    uint8_t inQuarter = step & (IRV_SINE_QUARTER - 1);
    uint8_t quarter = step / IRV_SINE_QUARTER;
    int32_t value;

    if (quarter & 1)
        value = gIrvSineQuarter[IRV_SINE_QUARTER - inQuarter];
    else
        value = gIrvSineQuarter[inQuarter];
    return (quarter & 2) ? -value : value;
}

int32_t IrvCosine(uint8_t step)
{
    return IrvSine((uint8_t)(step + IRV_SINE_QUARTER));
}
