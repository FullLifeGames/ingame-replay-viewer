    EXPECT_EQ(ValidateEnd(REPLAY_OUTCOME_UNKNOWN + 1), REPLAY_ERROR_OPERAND);
    EXPECT_EQ(ValidateEnd(REPLAY_OUTCOME_UNKNOWN), REPLAY_ERROR_NONE);
